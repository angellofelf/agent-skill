#!/usr/bin/env node

/**
 * @ai-generated
 * @date 2026-03-11
 * @description AI Code Stats 测试用例
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

// 颜色输出
const colors = {
  reset: '\x1b[0m',
  bright: '\x1b[1m',
  red: '\x1b[31m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  cyan: '\x1b[36m',
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

// 执行命令
function exec(command, cwd = process.cwd()) {
  try {
    return execSync(command, { encoding: 'utf-8', cwd }).trim();
  } catch (error) {
    return null;
  }
}

// 测试统计
let passed = 0;
let failed = 0;

function test(name, fn) {
  try {
    fn();
    log(`✅ ${name}`, 'green');
    passed++;
  } catch (error) {
    log(`❌ ${name}`, 'red');
    log(`   错误: ${error.message}`, 'red');
    failed++;
  }
}

function assertEqual(actual, expected, message) {
  if (actual !== expected) {
    throw new Error(`${message}: 期望 ${expected}, 实际 ${actual}`);
  }
}

function assertTrue(value, message) {
  if (!value) {
    throw new Error(message);
  }
}

// 主测试函数
function runTests() {
  log('\n🧪 AI Code Stats 测试套件', 'bright');
  log('========================\n', 'bright');

  const testDir = path.join(__dirname, 'test-repo');
  const scriptPath = path.join(__dirname, 'ai-code-stats.js');

  // 清理并创建测试目录
  if (fs.existsSync(testDir)) {
    fs.rmSync(testDir, { recursive: true });
  }
  fs.mkdirSync(testDir, { recursive: true });

  // 初始化 git 仓库
  exec('git init', testDir);
  exec('git config user.name "testuser"', testDir);
  exec('git config user.email "test@test.com"', testDir);

  // 测试 1: 检查脚本是否存在
  test('脚本文件存在', () => {
    assertTrue(fs.existsSync(scriptPath), 'ai-code-stats.js 应该存在');
  });

  // 测试 2: 检查脚本是否可以执行（无参数）
  test('脚本可以执行（无参数）', () => {
    // 创建一个测试文件并提交
    const testFile = path.join(testDir, 'test.js');
    fs.writeFileSync(testFile, '// test file\n', 'utf-8');
    exec('git add .', testDir);
    exec('git commit -m "initial commit"', testDir);

    // 运行脚本（应该在非 git 仓库中返回错误）
    const result = exec(`node "${scriptPath}"`, testDir);
    assertTrue(result !== null, '脚本应该能执行');
  });

  // 测试 3: 检查 AI 生成文件识别
  test('AI 生成文件识别', () => {
    const aiFile = path.join(testDir, 'ai-generated.js');
    fs.writeFileSync(aiFile, `/**
 * @ai-generated by testuser
 * @date 2026-03-11
 * @description 测试文件
 */

function test() {
  return 'hello';
}
`, 'utf-8');

    exec('git add .', testDir);
    exec('git commit -m "add ai generated file"', testDir);

    const result = exec(`node "${scriptPath}"`, testDir);
    assertTrue(result !== null, '脚本应该能识别 AI 生成文件');
    assertTrue(result.includes('AI 生成文件') || result.includes('AI 生成统计'), '输出应该包含 AI 统计信息');
  });

  // 测试 4: 检查 staged 模式
  test('staged 模式', () => {
    const stagedFile = path.join(testDir, 'staged.js');
    fs.writeFileSync(stagedFile, `// staged file
// @ai-generated-start
function staged() {}
// @ai-generated-end
`, 'utf-8');

    exec('git add .', testDir);

    const result = exec(`node "${scriptPath}" staged`, testDir);
    assertTrue(result !== null, 'staged 模式应该能执行');
    assertTrue(result.includes('暂存区') || result.includes('staged'), '输出应该包含暂存区信息');

    // 提交 staged 文件
    exec('git commit -m "add staged file"', testDir);
  });

  // 测试 5: 检查 commit 模式
  test('commit 模式', () => {
    const commitFile = path.join(testDir, 'commit-test.js');
    fs.writeFileSync(commitFile, `/**
 * @ai-generated by testuser
 * @date 2026-03-11
 */
function commitTest() {}
`, 'utf-8');

    exec('git add .', testDir);
    exec('git commit -m "test commit mode"', testDir);

    const commitHash = exec('git rev-parse HEAD', testDir);
    const result = exec(`node "${scriptPath}" commit ${commitHash}`, testDir);
    assertTrue(result !== null, 'commit 模式应该能执行');
    assertTrue(result.includes('指定 Commit') || result.includes(commitHash.substring(0, 7)), '输出应该包含 commit 信息');
  });

  // 测试 6: 检查 range 模式
  test('range 模式', () => {
    // 获取 HEAD 的父提交
    const parentHash = exec('git rev-parse HEAD~1', testDir);
    const headHash = exec('git rev-parse HEAD', testDir);

    if (parentHash && headHash) {
      const result = exec(`node "${scriptPath}" range ${parentHash}..${headHash}`, testDir);
      assertTrue(result !== null, 'range 模式应该能执行');
      assertTrue(result.includes('Commit 范围') || result.includes('range'), '输出应该包含 range 信息');
    }
  });

  // 测试 7: 检查报告生成
  test('报告生成', () => {
    const reportDir = path.join(testDir, 'AI-Generate', 'testuser');
    const hasReports = fs.existsSync(reportDir) && fs.readdirSync(reportDir).some(f => f.endsWith('.md'));
    assertTrue(hasReports, '应该生成报告文件');
  });

  // 测试 8: 检查重复统计防护
  test('重复统计防护', () => {
    const result1 = exec(`node "${scriptPath}"`, testDir);
    const result2 = exec(`node "${scriptPath}"`, testDir);
    assertTrue(result2 !== null, '第二次执行应该正常返回');
    assertTrue(result2.includes('已统计过') || result2.includes('跳过') || result2.includes('检测到'), '应该检测到重复统计');
  });

  // 测试 9: 检查参数解析
  test('参数解析 - 需求名', () => {
    const result = exec(`node "${scriptPath}" "测试需求"`, testDir);
    assertTrue(result !== null, '带需求名参数应该能执行');
    assertTrue(result.includes('测试需求'), '输出应该包含需求名');
  });

  // 测试 10: 检查参数解析 - 用户名
  test('参数解析 - 用户名', () => {
    const result = exec(`node "${scriptPath}" "测试需求2" customuser`, testDir);
    assertTrue(result !== null, '带用户名参数应该能执行');
    assertTrue(result.includes('customuser') || result.includes('统计人'), '输出应该包含用户名信息');
  });

  // 清理
  log('\n🧹 清理测试目录...', 'blue');
  process.chdir(__dirname);
  fs.rmSync(testDir, { recursive: true, force: true });

  // 输出测试结果
  log('\n========================', 'bright');
  log(`📊 测试结果: ${passed} 通过, ${failed} 失败`, passed === 10 ? 'green' : (failed > 0 ? 'red' : 'yellow'));
  log('========================\n', 'bright');

  process.exit(failed > 0 ? 1 : 0);
}

// 运行测试
runTests();
